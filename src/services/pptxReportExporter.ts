/**
 * PPTX Report Exporter — generates a PowerPoint presentation with key KPIs.
 */
import PptxGenJS from 'pptxgenjs';
import type { SimulationResult, FactoryModel, KPIData } from '../types';

const BLUE = '006FEE';
const GREEN = '17C964';
const RED = 'F31260';
const GRAY = '6B7280';
const DARK = '1F2937';

function pct(v: number): string {
  return (v * 100).toFixed(1) + '%';
}

function fmtTime(s: number): string {
  if (s >= 3600) return (s / 3600).toFixed(1) + 'h';
  if (s >= 60) return (s / 60).toFixed(0) + 'm';
  return s.toFixed(0) + 's';
}

export async function downloadPPTXReport(result: SimulationResult, model: FactoryModel) {
  const kpis = result.kpis as KPIData;
  const pptx = new PptxGenJS();
  pptx.author = 'FactorySim';
  pptx.title = `${model.name} - Simulation Report`;

  // Slide 1: Title
  const slide1 = pptx.addSlide();
  slide1.addShape(pptx.ShapeType.rect, { x: 0, y: 0, w: '100%', h: '100%', fill: { color: BLUE } });
  slide1.addText(model.name || 'Factory Simulation Report', {
    x: 0.5, y: 1.5, w: 9, h: 1.2,
    fontSize: 36, color: 'FFFFFF', bold: true, fontFace: 'Arial',
  });
  slide1.addText(`Simulation Results - ${new Date().toLocaleDateString()}`, {
    x: 0.5, y: 2.8, w: 9, h: 0.6,
    fontSize: 16, color: 'CCDDFF', fontFace: 'Arial',
  });
  slide1.addText('Generated by FactorySim', {
    x: 0.5, y: 4.5, w: 9, h: 0.4,
    fontSize: 12, color: 'AABBEE', fontFace: 'Arial',
  });

  // Slide 2: KPI Summary
  const slide2 = pptx.addSlide();
  slide2.addText('KPI Summary', { x: 0.5, y: 0.3, w: 9, h: 0.5, fontSize: 24, bold: true, color: DARK });

  const summaryRows: PptxGenJS.TableRow[] = [
    [
      { text: 'Metric', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Value', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
    ],
    [{ text: 'OEE' }, { text: pct(kpis.oee?.overall || 0) }],
    [{ text: 'Availability' }, { text: pct(kpis.oee?.availability || 0) }],
    [{ text: 'Performance' }, { text: pct(kpis.oee?.performance || 0) }],
    [{ text: 'Quality' }, { text: pct(kpis.oee?.quality || 0) }],
    [{ text: 'Throughput' }, { text: String(kpis.throughput?.total || 0) + ' units' }],
    [{ text: 'Rate' }, { text: (kpis.throughput?.ratePerHour || 0).toFixed(1) + ' /hr' }],
    [{ text: 'Avg Cycle Time' }, { text: fmtTime(kpis.cycleTime?.mean || 0) }],
    [{ text: 'WIP' }, { text: String(kpis.wip?.total || 0) }],
  ];

  if (kpis.cost) {
    summaryRows.push([{ text: 'Total Cost' }, { text: '$' + kpis.cost.totalCost.toFixed(2) }]);
    summaryRows.push([{ text: 'Cost / Unit' }, { text: '$' + kpis.cost.costPerUnit.toFixed(2) }]);
  }
  if (kpis.energy) {
    summaryRows.push([{ text: 'Energy' }, { text: kpis.energy.totalEnergy.toFixed(2) + ' kWh' }]);
  }

  slide2.addTable(summaryRows, {
    x: 0.5, y: 1.0, w: 9,
    fontSize: 12, fontFace: 'Arial',
    border: { type: 'solid', pt: 0.5, color: 'D1D5DB' },
    colW: [4.5, 4.5],
    rowH: 0.35,
    autoPage: false,
  });

  // Slide 3: OEE by Station
  const slide3 = pptx.addSlide();
  slide3.addText('OEE by Station', { x: 0.5, y: 0.3, w: 9, h: 0.5, fontSize: 24, bold: true, color: DARK });

  const oeeRows: PptxGenJS.TableRow[] = [
    [
      { text: 'Station', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Availability', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Performance', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Quality', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'OEE', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
    ],
  ];

  const stationOee = kpis.oee?.byStation || {};
  for (const station of model.stations) {
    const oee = stationOee[station.id];
    if (!oee) continue;
    const oeeVal = oee.oee;
    const cellColor = oeeVal >= 0.85 ? GREEN : oeeVal >= 0.60 ? 'F5A524' : RED;
    oeeRows.push([
      { text: station.name },
      { text: pct(oee.availability) },
      { text: pct(oee.performance) },
      { text: pct(oee.quality) },
      { text: pct(oee.oee), options: { bold: true, color: cellColor } },
    ]);
  }

  slide3.addTable(oeeRows, {
    x: 0.5, y: 1.0, w: 9,
    fontSize: 11, fontFace: 'Arial',
    border: { type: 'solid', pt: 0.5, color: 'D1D5DB' },
    colW: [3, 1.5, 1.5, 1.5, 1.5],
    rowH: 0.32,
    autoPage: false,
  });

  // Slide 4: Utilization
  const slide4 = pptx.addSlide();
  slide4.addText('Station Utilization', { x: 0.5, y: 0.3, w: 9, h: 0.5, fontSize: 24, bold: true, color: DARK });

  const utilRows: PptxGenJS.TableRow[] = [
    [
      { text: 'Station', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Busy', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Idle', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Blocked', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Failed', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Starved', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
    ],
  ];

  const utilByStation = kpis.utilization?.byStation || {};
  for (const station of model.stations) {
    const u = utilByStation[station.id] as any;
    if (!u) continue;
    utilRows.push([
      { text: station.name },
      { text: pct(u.busy || 0), options: { color: GREEN } },
      { text: pct(u.idle || 0) },
      { text: pct(u.blocked || 0), options: { color: u.blocked > 0.3 ? RED : GRAY } },
      { text: pct(u.failed || 0), options: { color: u.failed > 0.1 ? RED : GRAY } },
      { text: pct(u.starved || 0) },
    ]);
  }

  slide4.addTable(utilRows, {
    x: 0.5, y: 1.0, w: 9,
    fontSize: 10, fontFace: 'Arial',
    border: { type: 'solid', pt: 0.5, color: 'D1D5DB' },
    colW: [2.5, 1.3, 1.3, 1.3, 1.3, 1.3],
    rowH: 0.32,
    autoPage: false,
  });

  // Slide 5: Throughput
  const slide5 = pptx.addSlide();
  slide5.addText('Throughput Analysis', { x: 0.5, y: 0.3, w: 9, h: 0.5, fontSize: 24, bold: true, color: DARK });

  const tpRows: PptxGenJS.TableRow[] = [
    [
      { text: 'Metric', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
      { text: 'Value', options: { bold: true, color: 'FFFFFF', fill: { color: BLUE } } },
    ],
    [{ text: 'Total Completed' }, { text: String(kpis.throughput?.total || 0) }],
    [{ text: 'Rate (per hour)' }, { text: (kpis.throughput?.ratePerHour || 0).toFixed(1) }],
    [{ text: 'In Progress' }, { text: String(kpis.throughput?.inProgress || 0) }],
  ];

  if (kpis.throughput?.byProduct) {
    for (const [product, count] of Object.entries(kpis.throughput.byProduct)) {
      tpRows.push([{ text: `  Product: ${product}` }, { text: String(count) }]);
    }
  }

  slide5.addTable(tpRows, {
    x: 0.5, y: 1.0, w: 9,
    fontSize: 12, fontFace: 'Arial',
    border: { type: 'solid', pt: 0.5, color: 'D1D5DB' },
    colW: [4.5, 4.5],
    rowH: 0.35,
    autoPage: false,
  });

  // Slide 6: Recommendations
  const slide6 = pptx.addSlide();
  slide6.addText('Recommendations & Warnings', { x: 0.5, y: 0.3, w: 9, h: 0.5, fontSize: 24, bold: true, color: DARK });

  const warnings = kpis.warnings || [];
  if (warnings.length > 0) {
    const bulletItems = warnings.slice(0, 10).map(w => ({
      text: w.message,
      options: { fontSize: 11, color: w.severity === 'warning' ? RED : GRAY, bullet: true } as PptxGenJS.TextPropsOptions,
    }));
    slide6.addText(bulletItems, {
      x: 0.5, y: 1.0, w: 9, h: 4,
      fontFace: 'Arial',
      paraSpaceAfter: 8,
    });
  } else {
    slide6.addText('No warnings or recommendations. The simulation completed successfully.', {
      x: 0.5, y: 2.0, w: 9, h: 1,
      fontSize: 14, color: GREEN, fontFace: 'Arial',
    });
  }

  // Save
  const filename = `factorysim-${(model.name || 'report').replace(/\s+/g, '-').toLowerCase()}-${new Date().toISOString().slice(0, 10)}.pptx`;
  await pptx.writeFile({ fileName: filename });
}
